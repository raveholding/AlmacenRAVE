# V26.57 · tarjeta digital a pantalla completa (#mitarjeta)
import sys
from playwright.sync_api import sync_playwright
res=[];errs=[]
def chk(c,m):print(('OK   ' if c else 'FALLA ')+m);res.append(bool(c))
URL=sys.argv[1] if len(sys.argv)>1 else 'file:///tmp/rave/index.html'
with sync_playwright() as p:
    b=p.chromium.launch(args=['--no-proxy-server']);ctx=b.new_context(viewport={'width':390,'height':844},accept_downloads=True);pg=ctx.new_page();ev=pg.evaluate
    pg.on('pageerror',lambda e:errs.append(str(e)[:200]))
    pg.goto(URL+'#menu');pg.wait_for_timeout(1500)
    cid=ev("(()=>{const c=S.customers.find(c=>c.status!=='baja'&&cardIdOk(c.id)&&c.secret)||S.customers.find(c=>c.status!=='baja');return c.id})()")
    ev("(()=>{const c=custById('%s');if(typeof walLoad==='function'){S.cfg.fid=S.cfg.fid||{};S.cfg.fid.wallet={on:true,rubro:'cobr'};fidMov().push({id:uid(),cust:c.id,ts:now(),kind:'carga',amount:123400,ref:'prueba',user:'t'});}for(let i=0;i<3;i++)S.loyalty.ledger.push({id:uid(),cust:c.id,ts:now()-i*864e5,kind:'stamp',n:1,ref:'t',user:'t'});save()})()"%cid)
    link=ev("pubCardPortable('%s').link"%cid)
    chk('#tarjeta=' in link,'el negocio arma el enlace personal de la tarjeta')
    pg.goto(URL+'#'+link.split('#',1)[1]);pg.wait_for_timeout(2000)
    fr=pg.frame_locator('#pubframe')
    chk(ev("location.hash")=='#mitarjeta','al abrir el enlace queda en #mitarjeta (la tarjeta, no el menú)')
    chk(fr.locator('#mt-full').count()==1,'se abre la tarjeta digital a pantalla completa')
    t=fr.locator('#mt-full').inner_text()
    chk('tarjeta del club' in t.lower() and 'sellos' in t and 'Socio N' in t,'muestra nombre, N.º de socio y sellos')
    chk('1.234' in t,'muestra el crédito del monedero ($ 1.234)')
    chk(fr.locator('#mt-full a[href*="wa.me"]').count()>=2,'botones para escribir al local y consultar/reservar por WhatsApp')
    href=fr.locator('#mt-full a.wa').first.get_attribute('href')
    chk('socio' in href.lower() or 'soy' in href.lower(),'el mensaje al local ya dice quién es')
    fr.locator('#mt-code').click();pg.wait_for_timeout(400)
    chk(fr.locator('#mt-codebox svg').count()==1,'muestra el QR que cambia para sumar sellos')
    with pg.expect_download() as d: fr.locator('#mt-img').click()
    chk(d.value.suggested_filename=='mi-tarjeta-club.png','descarga la imagen para mostrar a los amigos')
    pg.screenshot(path='/tmp/rave/mt1.png',full_page=False)
    inv=ev("document.getElementById('pubframe').contentWindow.navigator.share?1:0")
    chk(not any('#tarjeta=' in x for x in [fr.locator('#mt-full').inner_html()]),'la pantalla no expone el enlace personal (invitar comparte el menú)')
    chk(ev("(()=>{const d=document.getElementById('pubframe').contentDocument;return d.documentElement.scrollWidth<=d.defaultView.innerWidth+1})()"),'no desborda a 390 px')
    fr.locator('#mt-menu').click();pg.wait_for_timeout(300)
    chk(fr.locator('#mt-full').count()==0 and ev("location.hash")=='#menu','«Ver el menú» cierra la tarjeta y vuelve al menú')
    pg.goto(URL+'#mitarjeta');pg.wait_for_timeout(1800)
    chk(pg.frame_locator('#pubframe').locator('#mt-full').count()==1,'#mitarjeta (acceso guardado en el inicio) abre directo la tarjeta')
    chk(pg.frame_locator('#pubframe').locator('#loy-full').count()==1,'en el menú, la tarjeta tiene «Abrir mi tarjeta digital»')
    chk(not errs,'sin errores %s'%errs[:2])
    b.close()
print('%d/%d'%(sum(res),len(res)))
