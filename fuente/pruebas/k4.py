    ev("go('fidel')");pg.wait_for_timeout(400)
    n=ev("S.customers.filter(c=>c.status!=='baja'&&c.consent&&c.consent.club!==false).length")
    rows=pg.locator('#fd-soc-t tbody tr[data-q]').count()
    chk(n>=3 and rows==n,'Fidelización lista los %d socios del Club (%d filas)'%(n,rows))
    chk('Juan Demostración' in pg.inner_text('#fd-soc'),'se ven los nombres y los sellos de cada socio')
    pg.fill('#fd-q','juan');pg.wait_for_timeout(200)
    chk(pg.locator('#fd-soc-t tbody tr[data-q]:not([hidden])').count()==1,'el buscador filtra los socios')
    pg.fill('#fd-q','');pg.wait_for_timeout(100)
    chk(pg.locator('#fd-soc [data-act=cuDel]').count()==rows and pg.locator('#fd-soc [data-act=cuCardLink]').count()>=1,'cada socio tiene «Enviar tarjeta» y «Eliminar» para el administrador')
    # ---------- 2. Enviar tarjeta con Wallet ----------
    ev("A.cuCardLink({dataset:{id:'demo2'}})");pg.wait_for_timeout(300)
    t=pg.inner_text('#modal-root')
    chk('Enviar tarjeta' in t and 'Apple Wallet' in t and 'Google Wallet' in t,'«Enviar tarjeta» ofrece Apple Wallet y Google Wallet')
    href=pg.locator('#cl-wa').get_attribute('href') or ''
    chk('Wallet' in __import__('urllib.parse').parse.unquote(href),'el mensaje de WhatsApp le dice al cliente que puede guardarla en Wallet')
    pg.click('[data-act=walPrev][data-k=apple]');pg.wait_for_timeout(300)
    t=pg.locator('#modal-root .ov >> nth=-1').inner_text()
    chk('SIMULACIÓN' in t and 'Apple Wallet' in t and 'Juan' in t and pg.locator('#modal-root .ov >> nth=-1').locator('svg').count()>=1,'vista del pase de Apple Wallet (simulación rotulada, con nombre y QR)')
    close();ev("A.cuCardLink({dataset:{id:'demo2'}})");pg.wait_for_timeout(300)
    pg.click('[data-act=walPrev][data-k=google]');pg.wait_for_timeout(300)
    t=pg.locator('#modal-root .ov >> nth=-1').inner_text()
    chk('SIMULACIÓN' in t and 'Google Wallet' in t and 'Sellos' in t,'vista del pase de Google Wallet (simulación rotulada)')
    close()
    r=ev("(()=>{const c=custById('demo2');const cid=(c.cards||[]).find(cardIdOk);const code=walletData(c,cid).code;const r=resolveStamp(code,'');return{code,ok:r.ok,cust:r.cust&&r.cust.id,msg:r.msg||''}})()")
    chk(r['code'].startswith('RAVE2N|') and (r['ok'] or 'hoy' in r['msg'] or '24' in r['msg']),'el código del pase es la tarjeta fija del socio y el mostrador lo reconoce (%s)'%r)
