    ev("A.cuDel({dataset:{id:'demo3'}})");pg.wait_for_timeout(300)
    pg.fill('#dl-m','Cierra su cuenta');pg.fill('#dl-n','3');last_ok()
    chk(ev("!!custById('demo3')") and 'deuda' in pg.locator('#modal-root .ov >> nth=-1').inner_text().lower(),'con deuda no se elimina sin decidir qué hacer con la deuda')
    pg.check('input[name=dl-d][value=condonar]');last_ok()
    chk(ev("!custById('demo3')") and ev("S.fiadoPays.some(p=>p.cust==='demo3'&&p.method==='condonado')"),'condonando la deuda (movimiento compensatorio) se elimina')
    chk(ev("S.audit.some(a=>a.action==='CLIENTE_ELIMINADO')"),'queda en la auditoría')
