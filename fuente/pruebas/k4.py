    ev("localStorage.setItem('rave.card','%s')"%cid);ev("location.hash='#menu'");pg.wait_for_timeout(900)
    ev("document.getElementById('pubframe').contentWindow.RAVE_CARD_REFRESH()");pg.wait_for_timeout(400)
    fr=pg.frame_locator('#pubframe')
    if fr.locator('#age-gate.open').count(): fr.locator('#ag-yes').click();pg.wait_for_timeout(300)
    chk(fr.locator('#loy-apple').count()==1 and fr.locator('#loy-google').count()==1,'la tarjeta del cliente en el menú tiene «Agregar a Apple Wallet» y «Guardar en Google Wallet»')
    fr.locator('#loy-google').click();pg.wait_for_timeout(400)
    tb=fr.locator('#loy-walbox').inner_text()
    chk('SIMULACIÓN' in tb and 'Google Wallet' in tb and 'Marta' in tb,'al tocarlo ve su pase (simulado en la demo)')
    fr.locator('#loy-apple').click();pg.wait_for_timeout(400)
    chk('Apple Wallet' in fr.locator('#loy-walbox').inner_text(),'y el de Apple Wallet')
    # ---------- 4. eliminar socios ----------
    ev("location.hash='#panel/fidel'");pg.wait_for_timeout(900)
    if pg.locator('#lu').is_visible():
        pg.select_option('#lu',index=0);pg.fill('#lp','1234');pg.click('[data-act=login]');pg.wait_for_timeout(600);ev("go('fidel')");pg.wait_for_timeout(300)
    hist=ev("custHistory(custById('demo2'))");ns=ev("S.sales.length")
    chk(len(hist)>0,'Juan tiene historial (%s)'%hist)
    ev("A.cuDel({dataset:{id:'demo2'}})");pg.wait_for_timeout(300)
    t=pg.locator('#modal-root .ov >> nth=-1').inner_text()
    chk('Eliminar definitivamente' in t and 'Tiene historial' in t,'con historial se puede eliminar, avisando qué se conserva')
    pg.fill('#dl-m','Pidió que lo borren');pg.fill('#dl-n','2');last_ok()
    chk(ev("!custById('demo2')"),'el administrador eliminó al socio con historial')
    chk(ev("S.sales.length")==ns and ev("!(S.members||[]).some(m=>m.cust==='demo2')"),'las ventas se conservan; su membresía se borra')
    ev("go('fidel')");pg.wait_for_timeout(300)
    v=pg.inner_text('#view')
    chk('Juan Demostración' not in v and 'Socio N.º 0002 (eliminado)' in v,'ya no aparece en Fidelización; sus sellos viejos dicen «socio eliminado»')
    ev("go('clientes')");pg.wait_for_timeout(300)
    chk('Juan Demostración' not in pg.inner_text('#view'),'tampoco aparece en Clientes')
    # con deuda: pide cobrar o condonar
    if not ev("!!openSess()"): ev("S.sessions.push({id:'sK4',caja:S.tenant.caja,openedBy:'ADMIN',openedAt:now(),opening:0,closedAt:0})")
    ev("(()=>{const c=custById('demo3');pos.lines=[];pos.cust='demo3';A.padd({dataset:{id:S.products.find(p=>p.unit==='u'&&!isKit(p)&&p.active).id}});return commitSale('fiado',false,'local',pos.lines,{custId:'demo3'})})()")
